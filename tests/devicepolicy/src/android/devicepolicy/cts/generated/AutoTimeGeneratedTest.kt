import com.android.bedstead.harrier.BedsteadJUnit4
import com.android.compatibility.common.util.ApiTest
import org.junit.runner.RunWith

// Policy definition that runs with POLICY_SCOPE_USER.
// Generated by running `cts-policy-tests-generator AUTO_TIME`.
@EnterprisePolicy(
    dpc = [],
    permissions = []
)
public final class AutoTimePolicy_ScopeUser {}

// Policy definition that runs with POLICY_SCOPE_DEVICE.
// Generated by running `cts-policy-tests-generator AUTO_TIME`.
@EnterprisePolicy(
    dpc =
        [
            APPLIED_BY_DEVICE_OWNER or APPLIES_GLOBALLY,
            APPLIED_BY_ORGANIZATION_OWNED_PROFILE_OWNER_PROFILE or APPLIES_GLOBALLY,
        ],
    permissions =
        [
            Permission(
                appliedWith =
                    [
                        "android.permission.SET_TIME",
                        "android.permission.MANAGE_DEVICE_POLICY_ACROSS_USERS",
                    ],
                appliesTo = APPLIES_GLOBALLY,
            ),
        ]
)
public final class AutoTimePolicy_ScopeDevice {}

// Policy definition that runs with POLICY_SCOPE_PARENT_USER.
// Generated by running `cts-policy-tests-generator AUTO_TIME`.
@EnterprisePolicy(
    dpc = [],
    permissions = []
)
public final class AutoTimePolicy_ScopeParentUser {}

@RunWith(BedsteadJUnit4::class)
@RequireFlagsEnabled(Flags.FLAG_POLICY_STREAMLINING, Flags.FLAG_POLICY_STREAMLINING_TESTS)
@UsesEnterprisePolicies(
    scopeUser = AutoTimePolicy_ScopeUser::class,
    scopeDevice = AutoTimePolicy_ScopeDevice::class,
    scopeParentUser = AutoTimePolicy_ScopeParentUser::class,
)
@ApiTest(
    apis =
        [
            "android.app.admin.PolicyIdentifier#AUTO_TIME",
            "android.app.admin.PolicyIdentifier#AUTO_TIME_DISABLED",
            "android.app.admin.PolicyIdentifier#AUTO_TIME_DISABLED_UNENFORCED",
            "android.app.admin.PolicyIdentifier#AUTO_TIME_ENABLED",
            "android.app.admin.PolicyIdentifier#AUTO_TIME_ENABLED_UNENFORCED",
            "android.app.admin.PolicyIdentifier#AUTO_TIME_USER_CHOICE",
        ]
)
class AutoTimeGeneratedTest : CommonPolicyTests<Int>() {

    override val policyIdentifier = PolicyIdentifier.AUTO_TIME

    override val validValues =
        listOf(
            PolicyIdentifier.AUTO_TIME_USER_CHOICE,
            PolicyIdentifier.AUTO_TIME_DISABLED_UNENFORCED,
            PolicyIdentifier.AUTO_TIME_ENABLED_UNENFORCED,
            PolicyIdentifier.AUTO_TIME_DISABLED,
            PolicyIdentifier.AUTO_TIME_ENABLED,
        )

    override val invalidValueTestCases =
        listOf(
            InvalidValueTestCase(-1), // Lower than lowest value
            InvalidValueTestCase(5), // Higher than highest value
        )
}
