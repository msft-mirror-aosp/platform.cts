@RunWith(BedsteadJUnit4::class)
@RequireFlagsEnabled(Flags.FLAG_POLICY_STREAMLINING, Flags.FLAG_POLICY_STREAMLINING_TESTS)
@UsesEnterprisePolicies(
    scopeUser = AppUninstallPolicyScopeUser::class,
    scopeDevice = AppUninstallPolicyScopeDevice::class,
    scopeParentUser = AppUninstallPolicyScopeParentUser::class,
)
@ApiTest(
    apis =
        [
            "android.app.admin.PolicyIdentifier#APP_UNINSTALL",
            "android.app.admin.PolicyIdentifier#APP_UNINSTALL_ALLOWED",
            "android.app.admin.PolicyIdentifier#APP_UNINSTALL_DISALLOWED",
        ]
)
class AppUninstallGeneratedTest : CommonPolicyTests<Int>() {

    override val policyIdentifier = PolicyIdentifier.APP_UNINSTALL

    override val validValues =
        listOf(PolicyIdentifier.APP_UNINSTALL_ALLOWED, PolicyIdentifier.APP_UNINSTALL_DISALLOWED)

    override val invalidValueTestCases =
        listOf(
            InvalidValueTestCase(0), // Lower than lowest value
            InvalidValueTestCase(3), // Higher than highest value
        )

    override fun getDeviceState() = deviceState

    companion object {
        @Rule @ClassRule @JvmField val deviceState = DeviceState()
    }
}
