package com.android.os.cts.multiuser.messaging;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Result {
    public static final String REGEX =
            "Result:\\{name:(.*?),result:(true|false),data:(.*?),action:(" + Action.REGEX + ")\\}";
    public static final Pattern PARSE_PATTERN = Pattern.compile(REGEX);

    private final String mName;
    private final boolean mResult;
    private final Action mAction;
    private final String mData;

    public Result(String name, boolean result, Action action, String data) {
        this.mName = name;
        this.mResult = result;
        this.mAction = action;
        this.mData = data;
    }

    public String getName() {
        return mName;
    }

    public Action getAction() {
        return mAction;
    }

    public String getData() {
        return mData;
    }

    public boolean getResult() {
        return mResult;
    }

    /**
     * Constructor to deserialize from the custom string FORMAT.
     *
     * @param resultString String generated by the toString() method.
     * @throws IllegalArgumentException if the string doesn't match the expected FORMAT.
     */
    public Result(String resultString) {
        if (resultString == null) {
            throw new IllegalArgumentException("Input string cannot be null");
        }
        Matcher matcher = PARSE_PATTERN.matcher(resultString);
        if (matcher.matches()) {
            try {
                this.mName = matcher.group(1);
                this.mResult = "true".equals(matcher.group(2));
                this.mData = matcher.group(3);
                this.mAction = new Action(matcher.group(4));
            } catch (NumberFormatException e) {
                throw new IllegalArgumentException(
                        "Failed to parse integer values from string: " + resultString, e);
            }
        } else {
            throw new IllegalArgumentException(
                    "String does not match Action FORMAT: " + resultString);
        }
    }

    /**
     * Helper method to compare results of different results
     *
     * @param other - other Result to compare
     * @param withData - if false result data should be compared
     * @param withActionName - if false Action name will not be compared
     * @return true if Result are equals
     */
    public boolean compare(Result other, boolean withData, boolean withActionName) {
        return this.getName().equals(other.getName())
                && this.getResult() == other.getResult()
                && (this.getData().equals(other.getData()) || !withData)
                && this.getAction().compare(other.getAction(), withActionName);
    }

    @Override
    public String toString() {
        return String.format("Result:{name:%s,result:%s,data:%s,action:%s}", mName, mResult, mData, mAction);
    }
}
